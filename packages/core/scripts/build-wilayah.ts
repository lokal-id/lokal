// Converts cahyadsn/wilayah's `db/wilayah.sql` (MIT, Kepmendagri codes) into the
// compact JSON files shipped in `data/` plus the generated `src/provinces.ts`.
//
// Optionally also cahyadsn/wilayah_kodepos's `db/wilayah_kodepos.sql` (MIT) for `data/kodepos.json`.
//
// Usage: node scripts/build-wilayah.ts <path/to/wilayah.sql> [path/to/wilayah_kodepos.sql]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const sqlPath = process.argv[2];
const kodeposPath = process.argv[3];
if (!sqlPath) {
  console.error('Usage: node scripts/build-wilayah.ts <path/to/wilayah.sql> [path/to/wilayah_kodepos.sql]');
  process.exit(1);
}

const dataDir = new URL('../data/', import.meta.url);
const sql = readFileSync(sqlPath, 'utf8');
const row = /\('([0-9.]+)',\s*'((?:[^'\\]|\\.|'')*)'\)/g;

const base: Record<string, string> = {};
const desa: Record<string, string> = {};
let count = 0;

for (const m of sql.matchAll(row)) {
  const code = m[1]!;
  const name = m[2]!.replace(/\\'/g, "'").replace(/''/g, "'").replace(/\s+/g, ' ').trim();
  const level = code.split('.').length;
  if (!/^\d{2}(?:\.\d{2}(?:\.\d{2}(?:\.\d{4})?)?)?$/.test(code) || !name) {
    throw new Error(`Invalid wilayah entry: ${code}`);
  }
  const target = level === 4 ? desa : base;
  if (Object.hasOwn(target, code)) throw new Error(`Duplicate wilayah code: ${code}`);
  target[code] = name;
  count++;
}

const levels = [1, 2, 3].map((level) => Object.keys(base).filter((code) => code.split('.').length === level).length);
if (levels.includes(0) || !Object.keys(desa).length) throw new Error('The wilayah input must include all four levels.');
for (const code of [...Object.keys(base), ...Object.keys(desa)]) {
  const lastDot = code.lastIndexOf('.');
  if (lastDot >= 0 && !Object.hasOwn(base, code.slice(0, lastDot))) {
    throw new Error(`Missing parent for wilayah code: ${code}`);
  }
}

const sortKeys = (entries: Record<string, string>) =>
  Object.fromEntries(Object.entries(entries).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));

const kodepos: Record<string, string> = {};
const postalUrl = new URL('kodepos.json', dataDir);
const postalInput = readFileSync(kodeposPath ?? postalUrl, 'utf8');
if (kodeposPath) {
  for (const m of postalInput.matchAll(/\('([0-9.]+)',\s*'([^']*)'\)/g)) {
    const [, code, postal] = m;
    if (Object.hasOwn(kodepos, code!)) throw new Error(`Duplicate kode pos mapping: ${code}`);
    kodepos[code!] = postal!;
  }
} else {
  Object.assign(kodepos, JSON.parse(postalInput));
}
for (const [code, postal] of Object.entries(kodepos)) {
  if (!Object.hasOwn(desa, code)) throw new Error(`Kode pos has no matching desa/kelurahan: ${code}`);
  if (typeof postal !== 'string' || !/^\d{5}$/.test(postal)) throw new Error(`Invalid kode pos for: ${code}`);
}
const missing = Object.keys(desa).filter((code) => !Object.hasOwn(kodepos, code));
if (missing.length) throw new Error(`Missing kode pos for ${missing.length} desa/kelurahan, including ${missing[0]}. Supply an updated mapping.`);

const provinces = Object.entries(sortKeys(base)).filter(([code]) => !code.includes('.'));
const ts = `// Generated by scripts/build-wilayah.ts from cahyadsn/wilayah (Kepmendagri). Do not edit.
export const PROVINCES: Readonly<Record<string, string>> = {
${provinces.map(([code, name]) => `  '${code}': ${JSON.stringify(name)},`).join('\n')}
};
`;
// All input validation completes before replacing any generated file.
writeFileSync(new URL('wilayah.json', dataDir), JSON.stringify(sortKeys(base)));
writeFileSync(new URL('desa.json', dataDir), JSON.stringify(sortKeys(desa)));
writeFileSync(new URL('../src/provinces.ts', import.meta.url), ts);
if (kodeposPath) writeFileSync(postalUrl, JSON.stringify(sortKeys(kodepos)));

const sha256 = (input: string) => createHash('sha256').update(input).digest('hex');
console.log(`rows=${count} provinsi=${levels[0]} kab/kota=${levels[1]} kecamatan=${levels[2]} desa/kelurahan=${Object.keys(desa).length}`);
console.log(`kodepos=${Object.keys(kodepos).length} wilayah.sql SHA-256=${sha256(sql)} kodepos input SHA-256=${sha256(postalInput)}`);
